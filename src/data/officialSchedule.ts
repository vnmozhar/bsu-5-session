import { publicSubjects } from './publicSubjects'

export type ScheduleEventKind =
  | 'Лекция'
  | 'Семинар'
  | 'Практическое занятие'
  | 'Консультация'
  | 'Зачет'
  | 'Экзамен'

export interface OfficialScheduleEntry {
  subjectId?: string
  date: string
  time: string
  kind: ScheduleEventKind
  subject: string
  instructor: string
  group: string
  location?: string
  preparation?: string
}

type ScheduleTrack = 'ОБЩ' | 'СПС' | 'ХОЗ'
type StudyCohort =
  | '1-я группа'
  | '2-я группа'
  | '1-я группа, подгруппа 1'
  | '1-я группа, подгруппа 2'
  | '2-я группа, подгруппа 1'
  | '2-я группа, подгруппа 2'

const subjectIds = new Map(publicSubjects.map(({ id, name }) => [name, id]))

function event(
  date: string,
  time: string,
  track: ScheduleTrack,
  kind: ScheduleEventKind,
  subject: string,
  instructor: string,
  cohort?: StudyCohort,
): OfficialScheduleEntry {
  const subjectId = subjectIds.get(subject)

  return {
    ...(subjectId ? { subjectId } : {}),
    date,
    time,
    kind,
    subject,
    instructor,
    group: cohort ? `${track} · ${cohort}` : track,
  }
}

